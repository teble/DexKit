#include "vector_descriptor_cache.h"
#include <atomic>
#include <cstdio>
#include <latch>
#include <thread>

namespace {
void Require(bool ok, const char *message) {
    if (!ok) { std::fprintf(stderr, "Vector cache check failed: %s\n", message); std::abort(); }
}
std::string Text(uint32_t id) {
    if (id == 0) return {};
    if (id == 2 || id % 127 == 0) return std::string(4096, char('a' + id % 26));
    return "value-" + std::to_string(id);
}

template<bool Promote>
void CheckBounds() {
    for (uint32_t n : {0u, 1u, 31u, 32u, 33u, 1057u}) {
        dexkit::VectorDescriptorCache<Promote> cache;
        cache.Initialize(n, n + 3);
        size_t builds = 0;
        std::vector<std::string_view> borrowed;
        for (uint32_t id = 0; id < n; ++id) {
            borrowed.push_back(cache.template GetOrCreate<true>(id, [&] { ++builds; return Text(id); }));
            Require(!cache.template TryGet<true>(id), "sparse probe must not pretend to be a dense hit");
        }
        Require(builds == n, "one sparse construction per ID");
        Require(!cache.template IsDense<true>() && !cache.template IsDense<false>(), "no inline conversion");
        for (uint32_t id = 0; id < n; ++id) Require(borrowed[id] == Text(id), "borrow valid until boundary");
        borrowed.clear(); // End every old borrow before maintenance.
        cache.ConvertPending();
        const bool converted = cache.template IsDense<true>();
        Require(!cache.template IsDense<false>(), "untouched field domain remains empty");
        Require(builds == n, "conversion must not regenerate content eagerly");
        if constexpr (!Promote) Require(!converted && !cache.HasPending(), "no-promotion control");
        for (uint32_t id = 0; id < n; ++id) {
            Require(cache.template TryGet<true>(id) == nullptr, "new dense slots start unready");
            auto value = cache.template GetOrCreate<true>(id, [&] { ++builds; return Text(id); });
            Require(value == Text(id), "regenerated bytes");
            if (converted) Require(cache.template TryGet<true>(id)->data() == value.data(), "ready pointer identity");
        }
        Require(builds == n * (converted ? 2 : 1), "intentional generation rebuilding");
        auto field = cache.template GetOrCreate<false>(n + 2, [] { return std::string("last-field"); });
        Require(field == "last-field", "field has an independent non-multiple limit");
        Require(!cache.template IsDense<false>(), "field conversion is deferred");
#if DEXKIT_BENCHMARK_DIAGNOSTICS
        const auto stats = cache.GetStatistics();
        for (const auto &domain : stats.domains)
            Require(domain.calls - domain.hits == domain.sparse_builds + domain.dense_builds, "completed calls account for both generations");
        if (converted) {
            const auto &domain = stats.domains[0];
            Require(domain.bucket_bytes == 0 && domain.payload_owner_bytes == 0
                    && domain.block_bytes == 0 && domain.directory_bytes == 0
                    && domain.sparse_structural_bytes == 0 && domain.sparse_records == 0, "old storage completely freed");
            Require(domain.discarded_records == n && domain.conversions == 1, "one conversion discards the original generation");
            Require(domain.dense_object_bytes == n * sizeof(std::string), "fixed exact vector capacity on this ABI");
        }
#endif
    }
}

template<bool Promote>
void CheckConcurrency() {
    constexpr uint32_t n = 4096;
    dexkit::VectorDescriptorCache<Promote> cache;
    cache.Initialize(n, n);
    auto builds = std::make_unique<std::atomic<unsigned>[]>(n);
    for (uint32_t id = 0; id < n; ++id) builds[id].store(0);
    auto get = [&](uint32_t id) {
        return cache.template GetOrCreate<true>(id, [&] { ++builds[id]; return Text(id); });
    };
    std::array<std::string_view, 3> retained{get(0), get(1), get(2)};
    std::array<const char *, 3> addresses{retained[0].data(), retained[1].data(), retained[2].data()};
    std::atomic<bool> finished{false};
    std::latch start(1);
    std::thread observer([&] {
        start.wait();
        do {
            for (uint32_t i = 0; i < retained.size(); ++i)
                Require(retained[i] == Text(i) && retained[i].data() == addresses[i], "independent old-view reader");
        } while (!finished.load(std::memory_order_acquire));
    });
    std::vector<std::thread> writers;
    for (uint32_t worker = 0; worker < 8; ++worker) writers.emplace_back([&, worker] {
        start.wait();
        for (uint32_t id = worker; id < n; id += 8) Require(get(id) == Text(id), "concurrent sparse fill");
    });
    start.count_down();
    for (auto &writer : writers) writer.join();
    finished.store(true, std::memory_order_release); observer.join();
    for (uint32_t id = 0; id < n; ++id) Require(builds[id] == 1, "sparse factory uniqueness");
    retained = {}; addresses = {};
    cache.ConvertPending();
    if constexpr (!Promote) { Require(!cache.template IsDense<true>(), "control stays sparse"); return; }
    Require(cache.template IsDense<true>() && !cache.template IsDense<false>(), "only requested domain converts");
    std::latch race(1);
    writers.clear();
    for (unsigned worker = 0; worker < 8; ++worker) writers.emplace_back([&] {
        race.wait();
        Require(get(0).empty(), "concurrent empty-string first insertion");
    });
    race.count_down();
    for (auto &writer : writers) writer.join();
    Require(builds[0] == 2 && cache.template TryGet<true>(0) != nullptr, "empty string is a ready value, built once per generation");
    retained = {get(0), get(1), get(2)};
    addresses = {retained[0].data(), retained[1].data(), retained[2].data()};
    finished.store(false);
    std::thread dense_observer([&] {
        do {
            for (uint32_t i = 0; i < retained.size(); ++i)
                Require(retained[i] == Text(i) && retained[i].data() == addresses[i], "dense borrowed views survive other slot fills");
        } while (!finished.load(std::memory_order_acquire));
    });
    writers.clear();
    for (uint32_t worker = 0; worker < 8; ++worker) writers.emplace_back([&, worker] {
        for (uint32_t id = worker; id < n; id += 8) Require(get(id) == Text(id), "concurrent dense fill");
    });
    for (auto &writer : writers) writer.join();
    finished.store(true, std::memory_order_release); dense_observer.join();
    for (uint32_t id = 0; id < n; ++id) Require(builds[id] == 2, "exactly one construction in each generation");
    cache.ConvertPending();
    Require(cache.template TryGet<true>(1)->data() == addresses[1], "no reconversion after dense publication");
}

void CheckBudget() {
    dexkit::VectorDescriptorCache<true> cache;
    cache.Initialize(60000, 60000);
    uint32_t count = 0;
    while (!cache.HasPending() && count < 60000) {
        const auto id = count++;
        cache.GetOrCreate<true>(id, [] { return std::string("x"); });
    }
    Require(count > 0 && count <= 60000 && !cache.IsDense<true>(), "request at structural byte crossing");
#if DEXKIT_BENCHMARK_DIAGNOSTICS
    const auto before = cache.GetStatistics().domains[0];
    Require(before.sparse_structural_bytes >= before.conversion_base_bytes, "new whole-domain byte rule");
    Require(before.sparse_structural_bytes == before.bucket_bytes + before.payload_owner_bytes
            + before.block_bytes + before.directory_bytes, "actual reclaimable allocations reconcile");
    Require(before.sparse_char_bytes == 0, "SSO budget case");
    std::printf("VECTOR_BUDGET {\"records\":%u,\"sparse_bytes\":%zu,\"dense_base_bytes\":%zu,\"normal_fixed_bytes\":%zu}\n",
            count, before.sparse_structural_bytes, before.conversion_base_bytes, cache.FixedObjectBytes());
#else
    std::printf("VECTOR_BUDGET {\"records\":%u,\"normal_fixed_bytes\":%zu}\n", count, sizeof(cache));
#endif
    cache.ConvertPending();
    Require(cache.IsDense<true>() && !cache.IsDense<false>() && !cache.HasPending(), "whole method domain converts alone");
    Require(cache.TryGet<true>(count - 1) == nullptr, "previously cached last ID intentionally forgotten");
}
} // namespace

int main(int argc, char **argv) {
    if (argc == 5 && std::string_view(argv[1]) == "reject") {
        const auto limit = std::strtoul(argv[3], nullptr, 10);
        const auto id = uint32_t(std::strtoull(argv[4], nullptr, 10));
        dexkit::VectorDescriptorCache<true> cache;
        cache.Initialize(limit, limit);
        if (std::string_view(argv[2]) == "method") cache.TryGet<true>(id);
        else cache.GetOrCreate<false>(id, [] { return std::string("invalid"); });
        return 2;
    }
    Require(argc == 1, "arguments");
    CheckBounds<false>(); CheckBounds<true>();
    CheckConcurrency<false>(); CheckConcurrency<true>(); CheckBudget();
    std::puts("CHECK_VECTOR_CACHE {\"passed\":true}");
}
